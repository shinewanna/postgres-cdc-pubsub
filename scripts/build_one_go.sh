#!/usr/bin/env bash
# Rebuilds sql/00_one_go_test.sql = 01 (table + rows) + 02 (install) + 04 (scenarios).
# Optionally refreshes 02/03 from the cloud-functions repo first, so the test
# always runs the exact SQL that goes to V1:
#
#   scripts/build_one_go.sh                       # just rebuild 00
#   scripts/build_one_go.sh ~/App/cloud-functions # refresh 02/03, then rebuild 00
set -euo pipefail
cd "$(dirname "$0")/.."

if [ $# -ge 1 ]; then
    # This project's install adds the `sent` flag; refuse to overwrite it with a source that lacks it.
    if ! grep -q "sent        boolean" "$1/sql/v2_sync/001_install.sql"; then
        echo "Not refreshing: $1/sql/v2_sync/001_install.sql has no 'sent' flag yet (it would remove it here)." >&2
        exit 1
    fi
    cp "$1/sql/v2_sync/001_install.sql"   sql/02_install_change_log.sql
    cp "$1/sql/v2_sync/002_uninstall.sql" sql/03_uninstall_change_log.sql
fi

{
    echo "-- pg-cdc-pubsub: EVERYTHING IN ONE GO -- generated by scripts/build_one_go.sh, do not edit."
    echo "-- Recreates products + test rows, installs the trigger, runs every scenario."
    echo "-- DBeaver: database cdc_pubsub_test, open this file, Alt+X; read the last two result tabs."
    echo
    echo "-- ===================== 01_products_table.sql ====================="
    cat sql/01_products_table.sql
    echo
    echo "-- ===================== 02_install_change_log.sql ====================="
    cat sql/02_install_change_log.sql
    echo
    echo "-- ===================== 04_scenarios.sql ====================="
    cat sql/04_scenarios.sql
} > sql/00_one_go_test.sql

echo "wrote sql/00_one_go_test.sql"
